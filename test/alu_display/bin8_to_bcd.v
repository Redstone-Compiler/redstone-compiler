// unsigned 0..255. 8번의 add-3/shift를 조합회로로 펼친다.
module bin8_to_bcd(value, hundreds, tens, ones);
  input [7:0] value;
  output [3:0] hundreds, tens, ones;
  wire [11:0] stage0, stage1, stage2, stage3, stage4, stage5, stage6, stage7, stage8;
  wire [3:0] h0, t0, o0, h1, t1, o1, h2, t2, o2, h3, t3, o3, h4, t4, o4, h5, t5, o5, h6, t6, o6, h7, t7, o7;
  wire [11:0] adjusted0, adjusted1, adjusted2, adjusted3, adjusted4, adjusted5, adjusted6, adjusted7;
  assign stage0 = 12'd0;
  assign h0 = stage0[11:8] >= 4'd5 ? stage0[11:8] + 4'd3 : stage0[11:8];
  assign t0 = stage0[7:4] >= 4'd5 ? stage0[7:4] + 4'd3 : stage0[7:4];
  assign o0 = stage0[3:0] >= 4'd5 ? stage0[3:0] + 4'd3 : stage0[3:0];
  assign adjusted0 = {h0, t0, o0};
  assign stage1 = {adjusted0[10:0], value[7]};
  assign h1 = stage1[11:8] >= 4'd5 ? stage1[11:8] + 4'd3 : stage1[11:8];
  assign t1 = stage1[7:4] >= 4'd5 ? stage1[7:4] + 4'd3 : stage1[7:4];
  assign o1 = stage1[3:0] >= 4'd5 ? stage1[3:0] + 4'd3 : stage1[3:0];
  assign adjusted1 = {h1, t1, o1};
  assign stage2 = {adjusted1[10:0], value[6]};
  assign h2 = stage2[11:8] >= 4'd5 ? stage2[11:8] + 4'd3 : stage2[11:8];
  assign t2 = stage2[7:4] >= 4'd5 ? stage2[7:4] + 4'd3 : stage2[7:4];
  assign o2 = stage2[3:0] >= 4'd5 ? stage2[3:0] + 4'd3 : stage2[3:0];
  assign adjusted2 = {h2, t2, o2};
  assign stage3 = {adjusted2[10:0], value[5]};
  assign h3 = stage3[11:8] >= 4'd5 ? stage3[11:8] + 4'd3 : stage3[11:8];
  assign t3 = stage3[7:4] >= 4'd5 ? stage3[7:4] + 4'd3 : stage3[7:4];
  assign o3 = stage3[3:0] >= 4'd5 ? stage3[3:0] + 4'd3 : stage3[3:0];
  assign adjusted3 = {h3, t3, o3};
  assign stage4 = {adjusted3[10:0], value[4]};
  assign h4 = stage4[11:8] >= 4'd5 ? stage4[11:8] + 4'd3 : stage4[11:8];
  assign t4 = stage4[7:4] >= 4'd5 ? stage4[7:4] + 4'd3 : stage4[7:4];
  assign o4 = stage4[3:0] >= 4'd5 ? stage4[3:0] + 4'd3 : stage4[3:0];
  assign adjusted4 = {h4, t4, o4};
  assign stage5 = {adjusted4[10:0], value[3]};
  assign h5 = stage5[11:8] >= 4'd5 ? stage5[11:8] + 4'd3 : stage5[11:8];
  assign t5 = stage5[7:4] >= 4'd5 ? stage5[7:4] + 4'd3 : stage5[7:4];
  assign o5 = stage5[3:0] >= 4'd5 ? stage5[3:0] + 4'd3 : stage5[3:0];
  assign adjusted5 = {h5, t5, o5};
  assign stage6 = {adjusted5[10:0], value[2]};
  assign h6 = stage6[11:8] >= 4'd5 ? stage6[11:8] + 4'd3 : stage6[11:8];
  assign t6 = stage6[7:4] >= 4'd5 ? stage6[7:4] + 4'd3 : stage6[7:4];
  assign o6 = stage6[3:0] >= 4'd5 ? stage6[3:0] + 4'd3 : stage6[3:0];
  assign adjusted6 = {h6, t6, o6};
  assign stage7 = {adjusted6[10:0], value[1]};
  assign h7 = stage7[11:8] >= 4'd5 ? stage7[11:8] + 4'd3 : stage7[11:8];
  assign t7 = stage7[7:4] >= 4'd5 ? stage7[7:4] + 4'd3 : stage7[7:4];
  assign o7 = stage7[3:0] >= 4'd5 ? stage7[3:0] + 4'd3 : stage7[3:0];
