#!/bin/sh
# Generic NOR-template initial geometry; SAT selects deletion subsets.
# Ordinary exact windows compact the verified complete NBT afterwards.
set -eu
if [ "$#" -ne 1 ]; then
  printf 'Usage: %s FRESH_OUTPUT_DIRECTORY\n' "$0" >&2
  exit 2
fi
cd "$(dirname "$0")/../.."
unset CONSTRUCT_RESUME CONSTRUCT_NETLIST CONSTRUCT_COMPACT_ONLY
CONSTRUCT_WIDTH=33 CONSTRUCT_HEIGHT=7 \
CONSTRUCT_ORDER=smallest-cone CONSTRUCT_FLATTEN_POSITIVE=1 \
CONSTRUCT_ISOLATE_OUTPUTS=0 CONSTRUCT_MAX_FANIN=0 CONSTRUCT_GATE_BATCH=1 \
CONSTRUCT_STEP_VOCABULARY=1 CONSTRUCT_COMPRESS_COMPLEMENTS=1 \
CONSTRUCT_PARTIAL_ORS=1 CONSTRUCT_DRIVING_SEAMS=1 \
CONSTRUCT_REPEATER_SEAMS=1 CONSTRUCT_SCAFFOLD_SEAMS=1 \
CONSTRUCT_SEAM_PITCH=3 CONSTRUCT_PRIMARY_STRIDE=2 \
CONSTRUCT_GATE_SCAFFOLD=1 CONSTRUCT_CASE_RANK_LEVELS=8 \
CONSTRUCT_STAGE_LEVELS=48 CONSTRUCT_CANONICAL_RANKS=1 \
CONSTRUCT_SYMMETRY=1 CONSTRUCT_WINDOW=10 CONSTRUCT_MAX_WINDOW=10 \
CONSTRUCT_OVERLAP=0 CONSTRUCT_MAX_OVERLAP=0 \
CONSTRUCT_STEP_OPT_MS=0 CONSTRUCT_DELETE_MS=0 CONSTRUCT_RESTARTS=0 \
CONSTRUCT_STEP_SECONDS=60 CONSTRUCT_WORKERS=4 CONSTRUCT_BUDGET_SECONDS=3600 \
  cargo run --release --example whole_decoder_construct -- "$1"
