#!/usr/bin/env python3
"""Emit ordinary unsigned RTL with one shared ripple-carry add/sub chain."""
from pathlib import Path


def source(width):
    assert width in (1, 2, 4, 8)
    lines = ["// Generated by tools/alu_display/generate_add_sub.py.",
             "// subtract=0: a+b; subtract=1: a-b; c=carry / no-borrow.",
             "// One explicitly shared carry chain; no arithmetic-sharing pass assumed.",
             "module add_sub(a, b, subtract, y, c);", f"  input [{width-1}:0] a, b;",
             "  input subtract;", f"  output [{width-1}:0] y;", "  output c;",
             f"  wire [{width-1}:0] adjusted_b;",
             "  wire " + ", ".join(f"carry_{i}" for i in range(width+1)) + ";",
             "  wire " + ", ".join(f"propagate_{i}, sum_{i}" for i in range(width)) + ";",
             "  assign adjusted_b = b ^ {" + ", ".join(["subtract"]*width) + "};",
             "  assign carry_0 = subtract;"]
    for bit in range(width):
        lines.extend([f"  assign propagate_{bit} = a[{bit}] ^ adjusted_b[{bit}];",
                      f"  assign sum_{bit} = propagate_{bit} ^ carry_{bit};",
                      f"  assign carry_{bit+1} = (a[{bit}] & adjusted_b[{bit}]) | (propagate_{bit} & carry_{bit});"])
    lines.extend(["  assign y = {" + ", ".join(f"sum_{i}" for i in reversed(range(width))) + "};",
                  f"  assign c = carry_{width};", "endmodule", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    for width in (1, 2, 4, 8):
        path = Path(f"test/alu_display/add_sub{width}.v")
        path.write_text(source(width))
        print(path)
