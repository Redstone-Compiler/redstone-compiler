#!/usr/bin/env python3
"""Enumerate exact 4-input prime covers, then minimize shared recipe pin edges.

Digits 10..15 are OFF, never don't-care. Each segment chooses a minimum-term
SOP or POS prime cover. All combinations of these covers are compared; this
is not a claim of globally optimal arbitrary Boolean-network synthesis.
"""
from functools import reduce
from itertools import combinations, product
from pathlib import Path
import argparse

MASKS = (0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07, 0x7F, 0x6F, 0, 0, 0, 0, 0, 0)


def covers_for(target):
    cubes = []
    for literals in product((-1, 0, 1), repeat=4):
        covered = sum(1 << value for value in range(16)
                      if all(bit == -1 or (value >> index) & 1 == bit
                             for index, bit in enumerate(literals)))
        if not covered & ~target:
            cubes.append((literals, covered))
    primes = [(literals, covered) for literals, covered in cubes
              if not any(covered != other and covered & other == covered
                         for _, other in cubes)]
    for size in range(1, len(primes) + 1):
        covers = [tuple(literals for literals, _ in selected)
                  for selected in combinations(primes, size)
                  if reduce(int.__or__, (covered for _, covered in selected), 0) == target]
        if covers:
            return covers
    raise ValueError("constant outputs need a separate source recipe")


def options():
    result = []
    for segment in range(7):
        on = sum(1 << value for value in range(16) if MASKS[value] >> segment & 1)
        result.append([(mode, cover) for mode, target in (("sop", on), ("pos", on ^ 0xFFFF))
                       for cover in covers_for(target)])
    return result


def cost(selected):
    unique = {(mode, term) for mode, terms in selected for term in terms
              if sum(bit != -1 for bit in term) > 1}
    # A singleton literal is directly wired/absorbed by the final recipe.
    edges = sum(sum(bit != -1 for bit in term) for _, term in unique)
    edges += sum(len(terms) for _, terms in selected)
    return edges, len(unique) + 7, selected


def evaluate(mode, terms, value):
    matches = [all(bit == -1 or (value >> index) & 1 == bit
                   for index, bit in enumerate(term)) for term in terms]
    return any(matches) if mode == "sop" else not any(matches)


def expression(mode, term):
    literals = []
    for index, value in enumerate(term):
        if value == -1:
            continue
        positive = value == 1 if mode == "sop" else value == 0
        literals.append(("" if positive else "~") + f"digit[{index}]")
    return (" & " if mode == "sop" else " | ").join(literals)


def generate():
    choices = options()
    selected = min(product(*choices), key=cost)
    for digit in range(16):
        actual = sum(int(evaluate(mode, terms, digit)) << index
                     for index, (mode, terms) in enumerate(selected))
        assert actual == MASKS[digit], (digit, actual, MASKS[digit])
        for blank in (0, 1):
            assert (actual if not blank else 0) == (MASKS[digit] if not blank else 0)
    unique = sorted({(mode, term) for mode, terms in selected for term in terms
                     if sum(bit != -1 for bit in term) > 1})
    names = {key: f"term_{index}" for index, key in enumerate(unique)}
    edges, cells, _ = cost(selected)
    lines = ["// Generated by tools/alu_display/minimize_decoder.py.",
             "// Exact 4-input covers: invalid BCD 10..15 is OFF; no don't-care.",
             f"// Shared recipe estimate before blank: {cells} cells, {edges} input edges.",
             "module bcd_to_7seg(digit, blank, seg);",
             "  input [3:0] digit;", "  input blank;", "  output [6:0] seg;",
             "  wire " + ", ".join(names.values()) + ";", "  wire a, b, c, d, e, f, g;"]
    for key, name in names.items():
        lines.append(f"  assign {name} = {expression(*key)};")
    for index, (mode, terms) in enumerate(selected):
        operands = [names.get((mode, term), f"({expression(mode, term)})") for term in terms]
        joined = (" | " if mode == "sop" else " & ").join(operands)
        lines.append(f"  assign {chr(97 + index)} = ~blank & ({joined});")
    lines.extend(["  assign seg = {g, f, e, d, c, b, a};", "endmodule", ""])
    return "\n".join(lines), len(list(product(*choices))), edges, cells


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("test/alu_display/bcd_to_7seg_minimized.v"))
    args = parser.parse_args()
    text, combinations_count, edges, cells = generate()
    args.output.write_text(text)
    print(f"checked {combinations_count} combinations of minimum-term SOP/POS covers")
    print(f"16 digit values and blank=0/1 verified; estimated cells={cells}, input_edges={edges}")
    print(args.output)
